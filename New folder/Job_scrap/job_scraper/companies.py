def _linkedin(company: str, role: str = "SDET QA Automation") -> str:
    from urllib.parse import quote
    q = quote(f"{role} {company}")
    return f"https://www.linkedin.com/jobs/search/?keywords={q}&location=India&f_E=3"


def _naukri(company: str) -> str:
    from urllib.parse import quote
    return f"https://www.naukri.com/{quote(company.lower().replace(' ', '-'))}-jobs"


